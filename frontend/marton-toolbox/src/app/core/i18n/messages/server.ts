/** The API's exact English wording → key (built from the English table, so the two can't drift apart). */
export const SERVER_TEXTS: Record<string, string> = Object.fromEntries(
  Object.entries(server.en)
    .filter(([key, text]) => key.startsWith('srv.') && !text.includes('{'))
    .map(([key, text]) => [text, key]),
);

/** API messages with a variable part: the pattern pulls the value out, the key puts it back in the user's language. */
export const SERVER_PATTERNS: { re: RegExp; key: string; params: string[] }[] = [
  { re: /^Too many wrong password attempts\. Try again in (\d+) minutes?/, key: 'srv.locked_out', params: ['minutes'] },
  { re: /^Please choose a size for (.+)\.$/, key: 'srv.choose_size', params: ['name'] },
  { re: /^Size "(.+)" is listed twice\.$/, key: 'srv.size_twice', params: ['size'] },
  { re: /^Each message can be at most ([\d,.]+) characters\.$/, key: 'srv.ai_each_max', params: ['max'] },
  { re: /^You've used 100% of your (.+) pack's AI allowance/, key: 'srv.ai_limit', params: ['plan'] },
];
